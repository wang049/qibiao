def _set_run(run, *, size, bold=False, color=INK, name=CN):
    run.font.size = PptPt(size)
    run.font.bold = bold
    run.font.color.rgb = color
    run.font.name = name
    rPr = run._r.get_or_add_rPr()
    ea = rPr.find(pqn("a:ea"))
    if ea is None:
        ea = rPr.makeelement(pqn("a:ea"), {})
        rPr.append(ea)
    ea.set("typeface", name)


def _fill(shape, rgb):
    shape.fill.solid()
    shape.fill.fore_color.rgb = rgb
    shape.line.fill.background()


def _tb(slide, l, t, w, h, text, *, size=14, bold=False, color=INK, name=CN, align=PP_ALIGN.LEFT, anchor=MSO_ANCHOR.TOP):
    box = slide.shapes.add_textbox(l, t, w, h)
    tf = box.text_frame
    tf.word_wrap = True
    tf.auto_size = None
    try:
        tf._txBody.bodyPr.set("anchor", {MSO_ANCHOR.TOP: "t", MSO_ANCHOR.MIDDLE: "ctr", MSO_ANCHOR.BOTTOM: "b"}[anchor])
    except Exception:
        pass
    p = tf.paragraphs[0]
    p.alignment = align
    p.clear()
    run = p.add_run()
    run.text = text
    _set_run(run, size=size, bold=bold, color=color, name=name)
    return box


def _tb_multi(slide, l, t, w, h, lines, *, size=13, color=BODY, name=CN, spacing=1.05):
    """lines: list of str or (str, kwargs)."""
    box = slide.shapes.add_textbox(l, t, w, h)
    tf = box.text_frame
    tf.word_wrap = True
    tf.auto_size = None
    first = True
    for item in lines:
        if first:
            p = tf.paragraphs[0]
            first = False
        else:
            p = tf.add_paragraph()
        p.alignment = PP_ALIGN.LEFT
        p.space_after = PptPt(4)
        if isinstance(item, tuple):
            text, kw = item
        else:
            text, kw = item, {}
        p.clear()
        run = p.add_run()
        run.text = text
        _set_run(
            run,
            size=kw.get("size", size),
            bold=kw.get("bold", False),
            color=kw.get("color", color),
            name=kw.get("name", name),
        )
    return box


def _rect(slide, l, t, w, h, rgb):
    sh = slide.shapes.add_shape(1, l, t, w, h)  # rectangle
    _fill(sh, rgb)
    return sh


