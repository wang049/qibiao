def _set_doc_run_font(run, name="微软雅黑", size=11, bold=False, color=None):
    run.font.name = name
    run._element.rPr.rFonts.set(qn("w:eastAsia"), name)
    run.font.size = Pt(size)
    run.font.bold = bold
    if color:
        run.font.color.rgb = color


def _p(doc, text, *, size=11, bold=False, color=None, space_after=8, space_before=0):
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(space_after)
    p.paragraph_format.space_before = Pt(space_before)
    p.paragraph_format.line_spacing = 1.15
    run = p.add_run(text)
    _set_doc_run_font(run, size=size, bold=bold, color=color)
    return p


def _shade(cell, fill: str) -> None:
    from lxml import etree

    shd = etree.SubElement(cell._tc.get_or_add_tcPr(), qn("w:shd"))
    shd.set(qn("w:fill"), fill)
    shd.set(qn("w:val"), "clear")


def _fill_row(row, vals, widths, *, header=False, size=8) -> None:
    for i, v in enumerate(vals):
        cell = row.cells[i]
        cell.text = ""
        p = cell.paragraphs[0]
        p.paragraph_format.space_after = Pt(2)
        r = p.add_run(v)
        _set_doc_run_font(
            r,
            size=9 if header else size,
            bold=header or i in (0, 2),
            color=DocRGB(0xFF, 0xFF, 0xFF) if header else None,
        )
        cell.width = widths[i]
        if header:
            _shade(cell, "1D6A85")


