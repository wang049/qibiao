  function applyStaticI18n() {
    const lang = uiLang();
    const h = document.documentElement;
    h.lang = lang === "en" ? "en" : "zh-CN";
    h.setAttribute("data-lang", lang);
    document.title = t("app.title");
    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const key = el.getAttribute("data-i18n");
      if (!key) return;
      const val = t(key);
      const attr = el.getAttribute("data-i18n-attr");
      const asHtml = el.hasAttribute("data-i18n-html");
      if (attr) {
        attr.split(",").forEach((a) => {
          const name = a.trim();
          if (name) el.setAttribute(name, val);
        });
      }
      if (asHtml) el.innerHTML = val;
      else if (!attr && !el.querySelector("svg, input, select, textarea")) el.textContent = val;
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
      el.setAttribute("placeholder", t(el.getAttribute("data-i18n-placeholder")));
    });
  }

