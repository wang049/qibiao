  const PACK = { zh: ZH, en: EN };

  function langFromQuery() {
    try {
      const v = new URLSearchParams(location.search || "").get("lang");
      if (v === "en" || v === "zh") return v;
    } catch (e) { /* ignore */ }
    return "";
  }

  function uiLang() {
    const q = langFromQuery();
    if (q) return q;
    try {
      const p = JSON.parse(localStorage.getItem("electrical.prefs") || "{}") || {};
      if (p.lang === "en" || p.lang === "zh") return p.lang;
    } catch (e) { /* ignore */ }
    return "zh";
  }

  function t(key, vars) {
    const lang = uiLang();
    const pack = PACK[lang] || ZH;
    let s = pack[key];
    if (s == null) s = ZH[key];
    if (s == null) s = key;
    if (vars) {
      Object.keys(vars).forEach((k) => {
        s = String(s).split("{" + k + "}").join(String(vars[k]));
      });
    }
    return s;
  }

